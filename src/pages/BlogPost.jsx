function renderContent(text) {
  const paragraphs = text.trim().split('\n\n')
  return paragraphs.map((p, i) => {
    if (p.startsWith('## ')) {
      return <h2 key={i} style={{ fontFamily:'var(--f-display)', fontSize:'clamp(24px,3vw,36px)', fontWeight:400, letterSpacing:'-0.02em', margin:'48px 0 16px', color:'var(--ink)' }}>{p.replace('## ', '')}</h2>
    }
    if (p.startsWith('**') && p.endsWith('**')) {
      return <p key={i} style={{ fontWeight:600, marginBottom:16, fontSize:16, lineHeight:1.7, color:'var(--ink)' }}>{p.replace(/\*\*/g, '')}</p>
    }
    // Handle inline bold
    const parts = p.split(/(\*\*[^*]+\*\*)/)
    return (
      <p key={i} style={{ marginBottom:20, fontSize:17, lineHeight:1.75, color:'var(--ink-2)' }}>
        {parts.map((part, j) =>
          part.startsWith('**') && part.endsWith('**')
            ? <strong key={j} style={{ color:'var(--ink)', fontWeight:600 }}>{part.replace(/\*\*/g, '')}</strong>
            : part
        )}
      </p>
    )
  })
}

